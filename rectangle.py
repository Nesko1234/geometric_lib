def area(a, b):
    '''Функция принимает длины двух разных сторон прямоугольника(a, b) и возвращает площадь этого прямоугольника путем перемножения длин двух разных сторон этого прямоугольника(a * b)'''
    return a * b
def perimeter(a, b):
    '''Функция принимает длины двух разных сторон прямоугольника(a, b) и возвращает периметр этого прямоугольника путем сложения удвоенных длин двух разных сторон этого прямоугольника(2*(a + b))'''
    return 2 *(a + b)